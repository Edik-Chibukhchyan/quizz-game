fiftyButton.addEventListener("click", useFiftyFifty);


function useFiftyFifty() {

    if (fiftyUsed) {
        return;
    }

    fiftyUsed = true;

    const current = gameQuestions[currentQuestion];

    const wrongAnswers = [];

    answerButtons.forEach((button, index) => {

        if (index !== current.correct) {
            wrongAnswers.push(index);
        }

    });

    // Перемешиваем неправильные ответы
    wrongAnswers.sort(() => Math.random() - 0.5);

    // Убираем два неправильных ответа
    wrongAnswers.slice(0, 2).forEach(index => {
        answerButtons[index].style.visibility = "hidden";
    });

    fiftyButton.disabled = true;
}

changeButton.addEventListener("click", changeQuestion);


function changeQuestion() {

    if (changeUsed) {
        return;
    }

    changeUsed = true;

    const usedQuestions = gameQuestions;

    const availableQuestions = questions.filter(question => {
        return !usedQuestions.includes(question);
    });

    if (availableQuestions.length === 0) {
        return;
    }

    const randomIndex = Math.floor(
        Math.random() * availableQuestions.length
    );

    gameQuestions[currentQuestion] = availableQuestions[randomIndex];

    changeButton.disabled = true;

    showQuestion();
}

hintButton.addEventListener("click", useHint);


function useHint() {

    if (hintUsed) {
        return;
    }

    hintUsed = true;

    const current = gameQuestions[currentQuestion];

    const hintText = document.getElementById("hint-text");

    hintText.textContent = "💡 " + current.hint;
    hintText.classList.remove("hidden");

    hintButton.disabled = true;
}

