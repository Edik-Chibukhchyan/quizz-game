function showQuestion() {

    document.getElementById("hint-text").classList.add("hidden");

    startTimer();

    const current = gameQuestions[currentQuestion];

    questionNumber.textContent =
        `Հարց ${currentQuestion + 1} / 20`;

    questionText.textContent = current.question;

    answerButtons.forEach((button, index) => {

    button.textContent = current.answers[index];
    button.style.visibility = "visible";

    });

    answerButtons.forEach((button, index) => {

    button.onclick = () => checkAnswer(index);

    });
}

function startTimer() {

    clearInterval(timer);

    timeLeft = 60;

    updateTimer();

    timer = setInterval(() => {

        timeLeft--;

        updateTimer();

        if (timeLeft <= 0) {

            clearInterval(timer);

            currentQuestion++;

            if (currentQuestion < 10) {
                showQuestion();
            } else {
                endGame();
            }
        }

    }, 1000);
}

function updateTimer() {

    const minutes = Math.floor(timeLeft / 60);
    const seconds = timeLeft % 60;

    document.getElementById("timer").textContent =
        `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`;
}

function checkAnswer(selectedAnswer) {

    clearInterval(timer);

    const current = gameQuestions[currentQuestion];

    answerButtons.forEach(button => {
        button.disabled = true;
    });

    if (selectedAnswer === current.correct) {

        score++;

        answerButtons[selectedAnswer].classList.add("correct");

    } else {

        answerButtons[selectedAnswer].classList.add("wrong");
        answerButtons[current.correct].classList.add("correct");

    }

    setTimeout(() => {

        answerButtons.forEach(button => {
            button.classList.remove("correct", "wrong");
            button.disabled = false;
        });

        currentQuestion++;

        if (currentQuestion < 20) {
            showQuestion();
        } else {
            endGame();
        }

    }, 1000);
}

